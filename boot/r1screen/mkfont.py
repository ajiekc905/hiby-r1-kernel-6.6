"""mkfont.py — bake the r1screen bitmap fonts into font.h (dev-time only, needs Pillow).

r1screen is the firmware's crash / no-card screen: it must draw with nothing
from the card and nothing parsed at crash time, so its glyphs are baked in.
DejaVu Sans (DejaVuSans.ttf in $R1_FONT_DIR, Bitstream Vera license: embedding allowed),
4-bit alpha, ASCII + Cyrillic + a little punctuation at the log/body/title sizes,
only ":(" at the face size.

    R1_FONT_DIR=/path/to/fonts python3 mkfont.py > font.h
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TTF = os.environ.get("R1_FONT_DIR", os.path.join(REPO, "player", "data", "fonts")) + "/DejaVuSans.ttf"

TEXT = [c for c in range(0x20, 0x7F)] + list(range(0x400, 0x460)) + [
    0xA0, 0xAB, 0xB0, 0xB7, 0xBB, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2192]
SETS = [("small", 16, TEXT), ("body", 20, TEXT), ("title", 30, TEXT), ("face", 120, [ord(":"), ord("(")])]


def glyph(font, cp):
    ch = chr(cp)
    adv = round(font.getlength(ch))
    box = font.getbbox(ch)
    if box[2] <= box[0] or box[3] <= box[1]:
        return adv, 0, 0, 0, 0, b""
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255)
    px = im.tobytes()
    out = bytearray((w * h + 1) // 2)
    for i, v in enumerate(px):
        q = (v + 8) * 15 // 255 if v else 0
        q = min(q, 15)
        out[i >> 1] |= q << (4 if i & 1 else 0)
    return adv, w, h, x0, y0, bytes(out)


def main():
    o = sys.stdout
    o.write("/* generated by mkfont.py from DejaVuSans.ttf (Bitstream Vera license) — do not edit */\n")
    o.write("typedef struct { unsigned cp; unsigned char adv, w, h; signed char x, y; unsigned off; } rg_glyph;\n")
    o.write("typedef struct { int px, ascent, line; int n; const rg_glyph *g; const unsigned char *bits; } rg_font;\n")
    for name, px, cps in SETS:
        font = ImageFont.truetype(TTF, px)
        asc, desc = font.getmetrics()
        data = bytearray()
        rows = []
        for cp in sorted(set(cps)):
            adv, w, h, x, y, bits = glyph(font, cp)
            rows.append((cp, adv, w, h, x, y, len(data)))
            data += bits
        o.write(f"static const unsigned char rg_{name}_bits[{max(len(data), 1)}] = {{")
        for i, b in enumerate(data):
            if i % 24 == 0:
                o.write("\n")
            o.write(f"{b},")
        o.write("\n};\n")
        o.write(f"static const rg_glyph rg_{name}_g[{len(rows)}] = {{\n")
        for r in rows:
            o.write("{%d,%d,%d,%d,%d,%d,%d},\n" % r)
        o.write("};\n")
        o.write(f"static const rg_font rg_{name} = {{{px}, {asc}, {asc + desc}, {len(rows)}, rg_{name}_g, rg_{name}_bits}};\n")


if __name__ == "__main__":
    main()
